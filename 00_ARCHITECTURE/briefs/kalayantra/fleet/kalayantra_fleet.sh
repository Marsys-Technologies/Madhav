ts() { date -u +%Y-%m-%dT%H:%M:%SZ; }
log() { echo "$(ts) [sup:$1] $2" >> "$LOGD/supervisor.log"; }

refuse_secrets() {
  local v
  for v in DATABASE_URL KY_BUILDER_DATABASE_URL KY_OWNER_DATABASE_URL PGPASSWORD; do
    if [ -n "${!v:-}" ]; then echo "REFUSED: $v is set in the supervisor's environment. Secrets belong only to the executor's shell (charter §7)." >&2; exit 78; fi
  done
}

valid_lane() { case "$1" in sutradhara|adhikarin|v1|v2|v3|k1|k2|k3|k4|k5|k6|k7|k8) return 0 ;; *) echo "invalid lane: $1" >&2; return 2 ;; esac; }
role_of()   { case "$1" in sutradhara) echo SUTRADHARA;; adhikarin) echo ADHIKARIN;; v*) echo PARIKSAKA;; k*) echo KARAKA;; esac; }
stream_of() { case "$1" in sutradhara) echo S;; adhikarin) echo N;; v*) echo V;; k*) echo K;; esac; }
model_of()  { case "$1" in sutradhara) echo "$MODEL_SUTRADHARA";; adhikarin) echo "$MODEL_ADHIKARIN";; v*) echo "$MODEL_PARIKSAKA";; k*) echo "$MODEL_WORKER";; esac; }
effort_of() { case "$1" in sutradhara) echo "$EFFORT_SUTRADHARA";; adhikarin) echo "$EFFORT_ADHIKARIN";; v*) echo "$EFFORT_PARIKSAKA";; k*) echo "$EFFORT_WORKER";; esac; }

wanted() {   # wanted <file> <default-when-absent> <ceiling>  → an integer in [0, ceiling]; malformed → the default
  "$PY" - "$1" "$2" "$3" <<'PYEOF'
import pathlib, sys
p = pathlib.Path(sys.argv[1]); default = int(sys.argv[2]); ceiling = int(sys.argv[3])
try:
    n = int(p.read_text().strip(), 10) if p.exists() else default
except (OSError, ValueError):
    n = default
print(max(0, min(ceiling, n)))
PYEOF
}
workers_wanted()   { wanted "$RUN/KY_WORKERS" 0 "$WORKER_CEILING"; }
verifiers_wanted() { wanted "$RUN/KY_VERIFIERS" 1 3; }

# ---- the lane environment: an allow-list, a clean shell start-up, and an explicit tool path ------------------------
node_bin() {   # node comes from nvm on this machine; without the user's shell profile the lane needs its folder named
  if [ -s "$RUN/NODE_BIN" ] && [ -x "$(cat "$RUN/NODE_BIN")/node" ]; then cat "$RUN/NODE_BIN"; return 0; fi
  local d=""
  if [ -n "${KY_NODE_BIN:-}" ] && [ -x "$KY_NODE_BIN/node" ]; then d="$KY_NODE_BIN"
  elif command -v node >/dev/null 2>&1; then d="$(dirname "$(command -v node)")"
  else d="$(ls -d "$HOME"/.nvm/versions/node/*/bin 2>/dev/null | sort -V | tail -1)"; fi
  [ -n "$d" ] && [ -x "$d/node" ] || return 1
  printf '%s\n' "$d" > "$RUN/NODE_BIN"; echo "$d"
}
lane_path() { local nb; nb="$(node_bin)" || nb=""; echo "$KY_ROOT/bin${nb:+:$nb}:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"; }
no_wrappers() {   # $KY_ROOT/bin holds the campaign CLI only; a wrapper around git, gh, npm, psql or codex there is refused (the LOCAL_ONLY incident of 2026-10-07)
  local f bad=""
  for f in "$KY_ROOT"/bin/*; do case "$(basename "$f")" in ky|kybrief) ;; *) bad="$bad $(basename "$f")";; esac; done
  [ -z "$bad" ] || { echo "REFUSED: $KY_ROOT/bin carries tool wrappers ($bad); only ky and kybrief belong there" >&2; return 78; }
}
ensure_shell_home() {   # the agent's shell must not source the user's ~/.zshrc (it exports personal keys): ZDOTDIR points here
  mkdir -p "$SHELL_HOME" || return 1
  printf '# KĀLA-YANTRA lane shell start-up (generated). Nothing personal is sourced.\nexport PATH="%s"\n' "$(lane_path)" > "$SHELL_HOME/.zshenv"
  printf '# generated; intentionally empty apart from the path\nexport PATH="%s"\n' "$(lane_path)" > "$SHELL_HOME/.zprofile"
  : > "$SHELL_HOME/.zshrc"; : > "$SHELL_HOME/.zlogin"
}
lane_env() {   # lane_env <lane> <stream> → fills the array LANE_ENV (the ONLY variables a lane's Codex process starts with)
  LANE_ENV=( "HOME=$HOME" "PATH=$(lane_path)" "LANG=en_US.UTF-8" "LC_ALL=en_US.UTF-8" "TERM=dumb" "USER=$(id -un)" "LOGNAME=$(id -un)" "SHELL=/bin/zsh"
             "TMPDIR=${TMPDIR:-/tmp}" "ZDOTDIR=$SHELL_HOME" "BASH_ENV=" "ENV="
             "KY_STREAM=$2" "KY_LANE=$1" "KY_ROOT=$KY_ROOT" "KY_PY=$KY_ROOT/venv/bin/python"
             "SE_EPHE_PATH=$SE_EPHE_PATH" "SWE_EPHE_PATH=$SE_EPHE_PATH" "CODEX_HOME=$HOME/.codex" )
}

ensure_worktree() {
  local wt="$WT/$1"
  if [ ! -e "$wt/.git" ]; then
    git -C "$KY_REPO_MAIN" fetch origin main -q || { log "$1" "FATAL: git fetch failed"; return 1; }
    git -C "$KY_REPO_MAIN" worktree add "$wt" --detach origin/main >/dev/null 2>&1 || { log "$1" "FATAL: cannot create worktree $wt"; return 1; }
    log "$1" "worktree created at $wt"
  fi
  [ -d "$wt/platform" ] || { log "$1" "FATAL: $wt is not a Madhav checkout"; return 1; }
  return 0
}

# ---- fleet-wide backoff and reservations (locked, fail-closed on malformed state) --------------------------------
quota_backoff_active() {
  "$PY" - "$RUN" <<'PYEOF'
import fcntl, pathlib, sys, time
root = pathlib.Path(sys.argv[1]); f = root / "KY_QUOTA_BACKOFF"
with (root / "backoff.lock").open("a+") as lock:
    fcntl.flock(lock, fcntl.LOCK_EX)
    if not f.exists(): sys.exit(1)
    try: until = int(f.read_text().strip())
    except ValueError: sys.exit(0)          # malformed → treat as active (fail closed); the supervisor logs it
    if time.time() < until: sys.exit(0)
    f.unlink(); sys.exit(1)
PYEOF
}
mark_quota_backoff() {
  "$PY" - "$RUN" "$KY_QUOTA_BACKOFF_S" <<'PYEOF'
import fcntl, pathlib, sys, time
root = pathlib.Path(sys.argv[1]); f = root / "KY_QUOTA_BACKOFF"; new = int(time.time()) + int(sys.argv[2])
with (root / "backoff.lock").open("a+") as lock:
    fcntl.flock(lock, fcntl.LOCK_EX)
    try: cur = int(f.read_text().strip()) if f.exists() else 0
    except ValueError: cur = 0
    f.write_text(str(max(cur, new)))
PYEOF
  log "$1" "quota/rate-limit marker in the current cycle log — fleet backs off ${KY_QUOTA_BACKOFF_S}s"
}
quota_error_in() {   # true when one of the last 40 lines is a Codex ERROR line naming a usage/rate limit
  tail -n 40 "$1" 2>/dev/null | grep -qiE "^(ERROR|error)[: ].*(\"status\": ?429|status 429|usage limit|usage_limit|rate.?limit|quota|too many requests)|^.{0,40}you.?ve hit your usage limit"
}
reserve_cycle() {   # prints the cycle number; exit 75 when this lane group's daily cap is reached (builders and control lanes are counted apart)
  "$PY" - "$RUN" "$1" "$KY_MAX_CYCLES_PER_DAY" "$KY_MAX_CONTROL_CYCLES_PER_DAY" <<'PYEOF'
import datetime, fcntl, json, os, pathlib, sys
root = pathlib.Path(sys.argv[1]); lane = sys.argv[2]; cap_workers = int(sys.argv[3]); cap_control = int(sys.argv[4])
worker = lane.startswith("k")
with (root / "CYCLE_STARTS.lock").open("a+") as lock:
    fcntl.flock(lock, fcntl.LOCK_EX)
    p = root / "CYCLE_STARTS.jsonl"
    rows = [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []
    now = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")
    today = sum(1 for r in rows if r["ts"][:10] == now[:10] and r["lane"].startswith("k") == worker)
    if today >= (cap_workers if worker else cap_control): sys.exit(75)
    n = 1 + sum(1 for r in rows if r["lane"] == lane)
    with p.open("a") as out:
        out.write(json.dumps({"ts": now, "lane": lane, "cycle": n}) + "\n"); out.flush(); os.fsync(out.fileno())
    print(n)
PYEOF
}

