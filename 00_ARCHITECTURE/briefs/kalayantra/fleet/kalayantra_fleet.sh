  printf 'Reply with exactly the single word READY and stop. Do not run any command.\n' > "$out/reviewer.prompt"; : > "$out/reviewer.last"
  lane_env v1 V
  if env -i "${LANE_ENV[@]}" codex exec -p "$CODEX_PROFILE" -s read-only -C "$WT/v1" --skip-git-repo-check -m "$MODEL_PARIKSAKA" -c 'model_reasoning_effort="low"' -o "$out/reviewer.last" - < "$out/reviewer.prompt" > "$out/reviewer.log" 2>&1 && grep -q READY "$out/reviewer.last"; then
    echo "✓ reviewer model $MODEL_PARIKSAKA starts under profile $CODEX_PROFILE"
  else echo "✗ reviewer model $MODEL_PARIKSAKA did not start: $(grep -E '^ERROR|^Error' "$out/reviewer.log" | head -1 | cut -c1-200)"; rc=1; fi
  printf '{"ts":"%s","result":"%s","profile":"%s","worker_model":"%s","reviewer_model":"%s"}\n' "$(ts)" "$([ $rc -eq 0 ] && echo PASS || echo FAIL)" "$CODEX_PROFILE" "$MODEL_WORKER" "$MODEL_PARIKSAKA" > "$RUN/LANE_SMOKE.json"
  [ $rc -eq 0 ] && echo "LANE SMOKE PASS" || echo "LANE SMOKE FAIL"; return $rc
}

snapshot_self() {   # supervisors run from a snapshot, so an edit in the working tree can never change a running loop
  local live="$KY_ROOT/fleet_live"
  mkdir -p "$live" && rsync -a --delete "$BRIEF/fleet/" "$live/" || return 1
  echo "$live/kalayantra_fleet.sh"
}
up() {
  refuse_secrets
  [ -f "$HOLD" ] && { echo "HOLD exists at $HOLD; use: $0 resume"; return 1; }
  local lane runner
  no_wrappers || return 78
  runner="$(snapshot_self)" || { echo "cannot snapshot the fleet folder to $KY_ROOT/fleet_live"; return 1; }
  rm -f "$RUN/NODE_BIN"; node_bin >/dev/null || { echo "node was not found (set KY_NODE_BIN in fleet.env)"; return 1; }
  bash "$HERE/make_codex_profile.sh" && ensure_shell_home || { echo "cannot prepare the Codex profile or the lane shell"; return 1; }
  for lane in "${ALL_LANES[@]}"; do
    rm -f "$RUN/STOP_$lane"
    # double-fork into a new session: the loop survives the shell (or the Codex session) that started it
    "$PY" -c 'import os, sys
if os.fork(): os._exit(0)
os.setsid()
if os.fork(): os._exit(0)
log = os.open(sys.argv[3], os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o600); null = os.open(os.devnull, os.O_RDONLY)
os.dup2(null, 0); os.dup2(log, 1); os.dup2(log, 2)
os.execvp("bash", ["bash", sys.argv[1], "lane", sys.argv[2]])' "$runner" "$lane" "$LOGD/supervisor.$lane.out"
  done
  sleep 2; log fleet "up requested for ${#ALL_LANES[@]} lanes from $runner (locks dedupe)"; status
}
down() {
  local lane
  for lane in "${ALL_LANES[@]}"; do touch "$RUN/STOP_$lane"; done
  log fleet "down: STOP files written; active cycles finish within the cap"
  echo "Stop requested. Active cycles keep their watchdog and finish within ${MAX_CYCLE_SECS}s; loops then exit."
}

case "${1:-status}" in
  up) up ;;
  down) down ;;
  resume) rm -f "$HOLD"; for lane in "${ALL_LANES[@]}"; do rm -f "$RUN/STOP_$lane"; done; up ;;
  status) status ;;
  smoke) smoke ;;
  lane) refuse_secrets; locked_lane "${2:?lane name required}" ;;
  lane-locked) valid_lane "${2:?}" || exit 2; supervise_lane "$2" ;;
  *) echo "usage: $0 up|down|resume|status|smoke|lane <name>"; exit 2 ;;
esac
