  cat > "$out/worker.prompt" <<'EOP'
Run exactly this one shell command and reply with its output only, nothing else:
env | cut -d= -f1 | sort | tr "\n" " "; echo; for t in node npm gh docker psql git python3; do command -v $t >/dev/null 2>&1 && echo "tool:$t:ok" || echo "tool:$t:MISSING"; done
EOP
  : > "$out/worker.last"
  if env -i "${LANE_ENV[@]}" codex exec -p "$CODEX_PROFILE" -s read-only -C "$WT/k1" --skip-git-repo-check -m "$MODEL_WORKER" -c 'model_reasoning_effort="low"' -o "$out/worker.last" - < "$out/worker.prompt" > "$out/worker.log" 2>&1; then
    echo "✓ worker model $MODEL_WORKER starts under profile $CODEX_PROFILE"
  else echo "✗ worker model $MODEL_WORKER did not start: $(grep -E '^ERROR|^Error' "$out/worker.log" | head -1 | cut -c1-200)"; rc=1; fi
