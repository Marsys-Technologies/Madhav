#: bg_combustion_orbs, Saturn row (orb_degrees 15, deep_orb_degrees 12), as read.
COMBUSTION_ORBS = {"Saturn": {"orb": 15.0, "deep": 12.0}}

#: Pinned canonical scores (the values the lane's review pinned; equal to the stored
#: ga_condition_composite.condition_score read above), in AYANAMSHAS order.
SATURN_PINNED_SCORES = (0.683108, 0.691486, 0.697162, 0.68, 0.683108)
SUN_PINNED_SCORES = (0.303784, 0.302703, 0.317568, 0.286622, 0.303784)


def run_real_compute(graha: str, fx: dict[str, Any]) -> dict[str, Any]:
    """Run the writer's own helpers on one read-input fixture, in `build_ga_condition_substep`'s order.

    Returns every intermediate so a failing golden names the step that moved. The Sun is never combust
    (check_combustion returns (False, False) for it; the writer skips the arc for the Sun)."""
    dignity_d1 = cw.dignity_d1_from_sign(graha, fx["sign"], fx["degree_in_sign"])
    dignity_score = cw.DIGNITY_SCORES.get(dignity_d1)
    is_retrograde = fx["retro"] == "retrograde"

    is_combust = is_deeply_combust = False
    if graha != "Sun":
        arc = cw.compute_combustion_arc(fx["longitude"], fx["sun_longitude"])
        is_combust, is_deeply_combust = cw.check_combustion(
            graha, arc, COMBUSTION_ORBS, is_retrograde=is_retrograde
        )

    baladi = cw.avastha_baladi_from_degree(fx["degree_in_sign"])
    deeptaadi = cw.avastha_deeptaadi_from_dignity_and_state(dignity_d1, is_combust, is_retrograde)

    # the writer's spread shape is {varga: {"sign": ..., "dignity": ...}}; the composite reads only
    # the dignity label when no numeric score is stored (none is, in the chart_divisionals rows read)
    spread = {varga: {"dignity": label} for varga, label in fx["spread"].items()}
    varga_composite = cw._compute_varga_composite(spread)

    score, breakdown = cw.compute_condition_score_v1(
        dignity_score=dignity_score,
        deeptaadi=deeptaadi,
        baladi=baladi,
        is_combust=is_combust,
        is_deeply_combust=is_deeply_combust,
        is_retrograde=is_retrograde,
        varga_score=varga_composite,
    )
    return {
        "dignity_d1": dignity_d1,
        "dignity_score": dignity_score,
        "is_combust": is_combust,
        "is_deeply_combust": is_deeply_combust,
        "avastha_baladi": baladi,
        "avastha_deeptaadi": deeptaadi,
        "varga_dignity_composite": varga_composite,
        "condition_score": score,
        "breakdown": breakdown,
        "band": bands.score_band(score),
        "medical_label": med.indication_strength_from_score(score),
        "vastu_label": vas.compute_direction_impact(score),
    }


