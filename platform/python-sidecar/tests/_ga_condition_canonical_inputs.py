"""
_ga_condition_canonical_inputs.py -- shared test support for the Saturn / Sun condition-score goldens.

Not a test module (no test_ prefix; pytest does not collect it).

WHAT IS HERE. The INPUTS the real ga_condition compute path consumes for the canonical chart
482012f1-710e-4a25-994a-93821f5871aa, Saturn and Sun, on the five ayanamshas, plus the stored
intermediate and final values the path is expected to reproduce. Every number below was READ
(SELECT-only, as the read-only reader, 2026-10-02) from:

  chart_facts (graha_sign_attributes / graha_position, subjects SAT, SUN)
      -> sign, degree_in_sign, longitude_sidereal, retrograde_flag
  ga_condition_composite (build 7a6f34fb-d2ed-4b50-9c06-74613b3eb685; one row per ayanamsha x graha)
      -> varga_dignity_spread (the D1..D2700 dignity labels), and the stored outputs
         dignity_d1, avastha_baladi, avastha_deeptaadi, varga_dignity_composite, condition_score
  bg_combustion_orbs (Saturn) -> orb 15 / deep 12

Nothing is invented and nothing is derived by hand. The stored outputs are NOT fed to the band
function: `run_real_compute` runs the SAME helper functions `build_ga_condition_substep` calls, in the
same order, on the READ INPUTS, so the golden tests fail if any of them (dignity rules, the dignity /
deeptaadi / baladi score tables, the formula weights, the varga-composite weighting, the combustion
rule) changes the score or its band.

NOT COVERED. The database-bound halves of the writer cannot run in a unit test: `_load_graha_positions`,
`_load_varga_dignity_spread` (the chart_divisionals SELECT that produces the spread read here),
`_load_dignity_ref` / the bg_dignity_reference override (the golden uses the module constants, which the
writer falls back to when the table is unavailable; the stored dignities agree), and the orchestrator
transaction. A change in those shows only in an end-to-end rebuild, not here.
"""
