    CONSTRAINT kala_obstruction_override_score_check CHECK (((override_score >= (0)::double precision) AND (override_score <= (1)::double precision))),
    CONSTRAINT kala_obstruction_severity_check CHECK ((severity = ANY (ARRAY['mild'::text, 'moderate'::text, 'severe'::text]))),
    CONSTRAINT kala_obstruction_severity_score_check CHECK (((severity_score >= (0)::double precision) AND (severity_score <= (1)::double precision)))
);

