CREATE TEMP TABLE kala_obstruction (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chart_id uuid NOT NULL,
    convergence_id bigint,
    signal_id uuid,
    obstruction_type text NOT NULL,
    severity text NOT NULL,
    severity_score double precision NOT NULL,
    override_score double precision DEFAULT 0.0 NOT NULL,
    obstruction_detail jsonb DEFAULT '{}'::jsonb NOT NULL,
    source_citation text DEFAULT 'ka_vighnakara:v1.0'::text NOT NULL,
    computed_at timestamp with time zone DEFAULT now(),
