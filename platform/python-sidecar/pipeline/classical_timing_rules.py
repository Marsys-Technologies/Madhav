# seed_g29_rules — idempotent DB seeder
# ---------------------------------------------------------------------------

def seed_g29_rules(conn) -> int:
    """
    Seed G29_RULES into g29_timing_rules table.

    Idempotent: uses INSERT ... ON CONFLICT (rule_id) DO NOTHING.
    Returns the number of rows actually inserted (existing rows skipped).

    Args:
        conn: A psycopg2 connection object (or compatible).

    Returns:
        int: Count of rows inserted in this call.
    """
    inserted = 0
    with conn.cursor() as cur:
        for rule in G29_RULES:
            cur.execute(
                """
                INSERT INTO g29_timing_rules
                  (rule_id, source_text, rule_category, timing_system,
                   trigger_predicate, predicted_outcome, activation_window,
                   strength_qualifier, classical_citation, notes)
                VALUES (%(rule_id)s, %(source_text)s, %(rule_category)s, %(timing_system)s,
                        %(trigger_predicate)s, %(predicted_outcome)s, %(activation_window)s,
                        %(strength_qualifier)s, %(classical_citation)s, %(notes)s)
                ON CONFLICT (rule_id) DO NOTHING
                """,
                rule,
            )
            inserted += cur.rowcount
    conn.commit()
    return inserted
