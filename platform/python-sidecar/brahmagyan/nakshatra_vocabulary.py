"""
nakshatra_vocabulary.py -- the single Python source of the 27 nakshatra NAMES and the ONE normaliser
that turns any registered spelling into the canonical one.

CANONICAL FAMILY AND AUTHORITY. The canonical spelling is the L0 lexicon's: `name_en` of the
`bg_nakshatra` seed (`brahmagyan.l0_nakshatra.NAKSHATRAS_ENRICHED`, written to
`reference_nakshatra.name_en` by `l0_nakshatra.seed_nakshatra()`), which is also the
`canonical_name_en` of the L0 ontology (`brahmagyan.l0_ontology.NAK_DATA`). Three of the 27 are
spelled differently from the way the L1 name table (`pyjhora_adapter._names`) writes them:

    no.  5  canonical "Mrigasira"   (the L1 adapter writes "Mrigashira")
    no. 19  canonical "Moola"       (the L1 adapter writes "Mula")
    no. 23  canonical "Dhanishtha"  (the L1 adapter writes "Dhanishta")

SS N-548 (narrow shape): the canonical spelling is applied at the vocabulary / emitter boundary. The
ga_* writers that EMIT a nakshatra name pass the adapter's string through `normalize_nakshatra()`
before it reaches chart_facts; `pyjhora_adapter._names`, `pipeline.transit_search` and
`services.ka_graha_sancara.engine` are left byte-identical (unifying them at source waits for the
next naturally full rebuild). Every L1/L2/L3 table that names a nakshatra derives from
`CANONICAL_NAKSHATRA_NAMES` (CLAUDE.md §N.5 / §N.7 item 3: no wrapper-local constant shadows a
canonical value), and every lookup BY NAME goes through the normaliser: no raw `.index(name)`, no
`.get(name, 0)`.

THE NORMALISER. `normalize_nakshatra(name)` maps a registered spelling -- the canonical name, the
lexicon's `alt_names` and IAST name, the ontology's `canonical_name_sa` and synonyms, or one of the
three legacy L1 spellings -- onto the canonical name, ignoring case, whitespace, underscores, hyphens
and combining diacritics. It RAISES `UnknownNakshatraError` (a ValueError) for anything else: never a
silent default, never index 0 / Ashwini (CLAUDE.md §N.7 item 6, B.10). `nakshatra_index()` is the same
lookup returning the 1-based number. `canonical_nakshatra()` / `nakshatra_number()` are the Optional
forms (None instead of raising) for the few readers that must FLAG an unresolved name rather than
abort (e.g. kala_permission's `tara_unresolved`); they are thin wrappers on the normaliser, not a
second table.

AMBIGUOUS BARE NAMES (SS N-561). A bare token that belongs to more than one nakshatra -- "Purva",
"Uttara", "Phalguni", "Ashadha", "Bhadrapada", "Bhadra", ... -- names no nakshatra by itself. The set
`AMBIGUOUS_BARE_TOKENS` is COMPUTED from the same L0 sources (every single word of every registered
spelling, kept when two or more nakshatras own it) and must contain at least "purva" and "uttara".
Such a token RAISES `AmbiguousNakshatraError` (a subclass of UnknownNakshatraError, so every
raising caller still sees a ValueError and every Optional caller still sees None) -- never a
default. The lexicon registers bare "Purva" / "Uttara" as `alt_names` (and the ontology bare
"uttara" as a synonym); those registrations are SUPPRESSED here (`SUPPRESSED_AMBIGUOUS_ALIASES`),
not deleted: the L0 data is the lexicon owner's to change (PR-body follow-up), and editing it would
reopen L0 windows.

LEAF MODULE. The gochara / Kala / ga_* writers import this module and their whole-closure conformance tests forbid
any database code in the closure; the L0 seed modules carry their seeders' SQL, so this module reads a FROZEN,
constants-only copy of exactly the rows it needs (`brahmagyan/nakshatra_vocabulary_data.py`, generated by
platform/scripts/governance/freeze_nakshatra_vocabulary_data.py and pinned to the L0 sources by
tests/test_nakshatra_vocabulary_data_frozen.py). The authority is still the L0 lexicon / ontology.
"""
from __future__ import annotations

import unicodedata
from types import MappingProxyType
from typing import Mapping

from brahmagyan.nakshatra_vocabulary_data import LEXICON_ROWS, ONTOLOGY_ROWS  # frozen, constants-only copy of the two L0 seeds (see below)

#: The 27 canonical names, index 0 = Ashwini (nakshatra no. 1) ... index 26 = Revati (no. 27).
#: Abhijit (the 28th row of the seed) is not one of the 27.
CANONICAL_NAKSHATRA_NAMES: tuple[str, ...] = tuple(name_en for _nid, name_en, _sa, _alts in sorted(LEXICON_ROWS))
if len(CANONICAL_NAKSHATRA_NAMES) != 27 or len(set(CANONICAL_NAKSHATRA_NAMES)) != 27:  # pragma: no cover
    raise RuntimeError("bg_nakshatra seed must carry 27 distinct nakshatra names")

#: The spellings the L1 name table (`pyjhora_adapter._names.NAKSHATRA_NAMES`) writes for nakshatras
#: 5 / 19 / 23, mapped to the canonical spelling: the emit-side fold in the ga_* writers, the read-side
#: tolerance for facts stored before those writers canonicalised, and the three extra names migration
#: 1364 lets bo_nakshatra_semantic's integrity check accept. Each is ALSO a registered alias of the
#: lexicon / ontology (asserted at import below); this dict only names the three explicitly.
LEGACY_L1_SPELLINGS: dict[str, str] = {
    "Mrigashira": "Mrigasira",
    "Mula": "Moola",
    "Dhanishta": "Dhanishtha",
}


class UnknownNakshatraError(ValueError):
    """The name is not a registered spelling of any of the 27 nakshatras."""


class AmbiguousNakshatraError(UnknownNakshatraError):
    """The name is a bare token shared by two or more nakshatras (e.g. "Purva", "Phalguni"): it names none of them."""


def _fold(name: str) -> str:
    """NFKD-decompose, drop combining marks, case-fold, keep alphanumerics only -- so 'Purva Phalguni',
    'PurvaPhalguni', 'purva_phalguni' and 'Pūrva Phalgunī' share one key."""
    decomposed = unicodedata.normalize("NFKD", str(name))
    stripped = "".join(c for c in decomposed if not unicodedata.combining(c))
    return "".join(c for c in stripped.casefold() if c.isalnum())


def _registered_spellings() -> dict[str, list[tuple[str, str]]]:
    """canonical name -> [(raw spelling, source)] from the frozen copy of the two L0 seeds (lexicon + ontology)."""
    by_id = {nid: (name_en, name_sa_iast, alts) for nid, name_en, name_sa_iast, alts in LEXICON_ROWS if 1 <= nid <= 27}
    out: dict[str, list[tuple[str, str]]] = {}
    for _nid, (canon, name_sa_iast, alts) in sorted(by_id.items()):
        entries = out.setdefault(canon, [])
        entries.append((canon, "lexicon name_en"))
        if isinstance(name_sa_iast, str):
            entries.append((name_sa_iast, "lexicon name_sa_iast"))
        entries += [(alt, "lexicon alt_names") for alt in alts if isinstance(alt, str)]
    for nid, name_en, name_sa, synonyms in ONTOLOGY_ROWS:
        canon = by_id[nid][0]
        if name_en != canon:  # pragma: no cover
            raise RuntimeError(f"l0_ontology.NAK_DATA names nakshatra {nid} {name_en!r}; the lexicon says {canon!r}")
        out[canon].append((name_sa, "ontology canonical_name_sa"))
        out[canon] += [(syn, "ontology synonym") for syn in synonyms if isinstance(syn, str)]
    return out


def _ambiguous_bare_tokens(registered: dict[str, list[tuple[str, str]]]) -> frozenset[str]:
    """Every single word (folded) of every registered spelling that two or more nakshatras own."""
    owners: dict[str, set[str]] = {}
    for canon, entries in registered.items():
        for spelling, _source in entries:
            for word in spelling.replace("_", " ").replace("-", " ").split():
                key = _fold(word)
                if key:
                    owners.setdefault(key, set()).add(canon)
    return frozenset(token for token, canons in owners.items() if len(canons) > 1)


_REGISTERED: dict[str, list[tuple[str, str]]] = _registered_spellings()

#: Folded bare tokens shared by two or more nakshatras (SS N-561): computed, never hand-typed; must hold "purva" and "uttara".
AMBIGUOUS_BARE_TOKENS: frozenset[str] = _ambiguous_bare_tokens(_REGISTERED)
if not {"purva", "uttara"} <= AMBIGUOUS_BARE_TOKENS:  # pragma: no cover
    raise RuntimeError(f"the ambiguity set must contain 'purva' and 'uttara'; got {sorted(AMBIGUOUS_BARE_TOKENS)}")


def _build_synonyms() -> tuple[dict[str, str], dict[str, tuple[str, str]]]:
    """(folded spelling -> canonical name, suppressed ambiguous registrations: raw spelling -> (canonical, source));
    fails loudly on ambiguity between two canonical names."""
    table: dict[str, str] = {}
    sources: dict[str, str] = {}
    suppressed: dict[str, tuple[str, str]] = {}
    for canon, entries in _REGISTERED.items():
        for spelling, source in entries:
            key = _fold(spelling)
            if not key:
                continue
            if key in AMBIGUOUS_BARE_TOKENS:          # a bare "Purva" / "Uttara" registered to ONE nakshatra names three: refuse it
                suppressed[spelling] = (canon, source)
                continue
            if key in table and table[key] != canon:
                raise RuntimeError(
                    f"nakshatra spelling {spelling!r} ({source}) would resolve to both {table[key]!r} "
                    f"({sources[key]}) and {canon!r}: the alias map must be unambiguous")
            table.setdefault(key, canon)
            sources.setdefault(key, source)
    for legacy, canon in LEGACY_L1_SPELLINGS.items():
        if table.get(_fold(legacy)) != canon:  # pragma: no cover
            raise RuntimeError(f"legacy L1 spelling {legacy!r} is not a registered alias of {canon!r} in the lexicon / ontology")
    return table, suppressed


_SYNONYMS, _SUPPRESSED = _build_synonyms()

#: Read-only view of the alias map (folded spelling -> canonical name), for tests and reports.
NAKSHATRA_SYNONYMS: Mapping[str, str] = MappingProxyType(_SYNONYMS)
#: Registered spellings the normaliser REFUSES because they are ambiguous bare tokens: raw spelling -> (the one nakshatra the
#: L0 data registers it to, source). Owed to the lexicon / ontology owner as a follow-up; L0 data is not edited here.
SUPPRESSED_AMBIGUOUS_ALIASES: Mapping[str, tuple[str, str]] = MappingProxyType(_SUPPRESSED)

_INDEX_BY_CANONICAL: dict[str, int] = {n: i + 1 for i, n in enumerate(CANONICAL_NAKSHATRA_NAMES)}


def normalize_nakshatra(name: object) -> str:
    """THE normaliser: the canonical spelling of a registered nakshatra spelling.

    Raises TypeError for a non-string, AmbiguousNakshatraError for a bare token shared by several
    nakshatras, and UnknownNakshatraError (a ValueError; the ambiguous error is its subclass) for a
    string that is not a registered spelling of one of the 27 -- never a default."""
    if not isinstance(name, str):
        raise TypeError(f"nakshatra name must be a string, got {type(name).__name__}")
    key = _fold(name)
    if key in AMBIGUOUS_BARE_TOKENS:
        raise AmbiguousNakshatraError(
            f"ambiguous nakshatra name {name!r}: the bare token names more than one nakshatra (SS N-561); use the full name")
    canon = _SYNONYMS.get(key)
    if canon is None:
        raise UnknownNakshatraError(f"unknown nakshatra name {name!r}: not a registered spelling of any of the 27")
    return canon


def nakshatra_index(name: object) -> int:
    """The 1-based nakshatra number (1..27) of a registered spelling; raises like `normalize_nakshatra`."""
    return _INDEX_BY_CANONICAL[normalize_nakshatra(name)]


def canonical_nakshatra(name: object) -> str | None:
    """Optional form of `normalize_nakshatra`: None (never a guess) for a non-string or an unknown name."""
    try:
        return normalize_nakshatra(name)
    except (TypeError, UnknownNakshatraError):
        return None


def nakshatra_number(name: object) -> int | None:
    """Optional form of `nakshatra_index`: None for a non-string or an unknown name."""
    canon = canonical_nakshatra(name)
    return None if canon is None else _INDEX_BY_CANONICAL[canon]
