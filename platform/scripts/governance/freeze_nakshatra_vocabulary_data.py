#!/usr/bin/env python3
"""freeze_nakshatra_vocabulary_data.py -- regenerate brahmagyan/nakshatra_vocabulary_data.py (SS N-5xx, Engine finding on #3460).

`brahmagyan/nakshatra_vocabulary.py` must be a LEAF: its import closure may hold no database code, because the gochara,
Kala and ga_* writers import it and the writer-closure conformance tests (test_a53_writerbase_conformance, the digest
walker) scan every imported file, function-level imports included. The L0 seed modules it used to import
(`l0_nakshatra.py`, `l0_ontology.py`) carry the seeders' SQL and a `conn.commit()`. This script copies exactly the data
the normaliser needs out of them into a constants-only module; `tests/test_nakshatra_vocabulary_data_frozen.py`
re-derives the same rows from the L0 modules and fails when the frozen copy drifts.

WHO REGENERATES (CLAUDE.md N.7 item 3; Engine condition on #3460): the L0 OWNER, in the same change that edits
l0_nakshatra.py or l0_ontology.py, runs this generator (and `--check`, which exits 1 on any byte difference) as part of that
change's own tests. The normaliser never reads the L0 modules at runtime, so a stale frozen copy is a RED test
(tests/test_nakshatra_vocabulary_data_frozen.py), never a silent divergence. Run from the repo root:

    python platform/scripts/governance/freeze_nakshatra_vocabulary_data.py
"""
from __future__ import annotations

import pathlib
import sys

SIDECAR = pathlib.Path(__file__).resolve().parents[2] / "python-sidecar"
sys.path.insert(0, str(SIDECAR))
OUT = SIDECAR / "brahmagyan" / "nakshatra_vocabulary_data.py"


def derive() -> tuple[tuple, tuple]:
    from brahmagyan.l0_nakshatra import NAKSHATRAS_ENRICHED
    from brahmagyan.l0_ontology import NAK_DATA
    lexicon = tuple(
        (r["nakshatra_id"], r["name_en"], r["name_sa_iast"], tuple(r["alt_names"]))
        for r in sorted(NAKSHATRAS_ENRICHED, key=lambda r: r["nakshatra_id"]) if 1 <= r["nakshatra_id"] <= 27)
    ontology = tuple((nid, en, sa, tuple(syns)) for nid, en, sa, syns in sorted(NAK_DATA, key=lambda t: t[0]))
    return lexicon, ontology


def render(lexicon: tuple, ontology: tuple) -> str:
    def rows(t):
        return "\n".join(f"    {r!r}," for r in t)
    return f'''"""
nakshatra_vocabulary_data.py -- FROZEN, constants-only copy of the nakshatra rows the normaliser needs. GENERATED by
platform/scripts/governance/freeze_nakshatra_vocabulary_data.py from the two L0 seed modules; do not edit by hand.

Why a copy exists: brahmagyan/nakshatra_vocabulary.py must be a LEAF whose import closure holds no database code (the
gochara / Kala / ga_* writers import it and their whole-closure conformance tests forbid any `conn.commit()` etc. in the
closure), while the authorities -- `brahmagyan.l0_nakshatra.NAKSHATRAS_ENRICHED` (the bg_nakshatra seed) and
`brahmagyan.l0_ontology.NAK_DATA` (the bg_ontology seed) -- live beside their seeders' SQL. The authority is unchanged:
tests/test_nakshatra_vocabulary_data_frozen.py re-derives these rows from the L0 modules and fails when they drift
(then re-run the generator). This module imports nothing.
"""

#: (nakshatra_id, name_en, name_sa_iast, alt_names) for nakshatras 1..27 -- from NAKSHATRAS_ENRICHED (bg_nakshatra seed).
LEXICON_ROWS: tuple[tuple[int, str, str, tuple[str, ...]], ...] = (
{rows(lexicon)}
)

#: (nakshatra_id, canonical_name_en, canonical_name_sa, synonyms) -- from l0_ontology.NAK_DATA (bg_ontology seed).
ONTOLOGY_ROWS: tuple[tuple[int, str, str, tuple[str, ...]], ...] = (
{rows(ontology)}
)
'''


def main() -> int:
    lexicon, ontology = derive()
    text = render(lexicon, ontology)
    if "--check" in sys.argv:
        return 0 if OUT.read_text(encoding="utf-8") == text else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(lexicon)} lexicon rows, {len(ontology)} ontology rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
