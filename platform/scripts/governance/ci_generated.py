#!/usr/bin/env python3
"""A5 D-33: publish deterministic generated overlays, bound to the reviewed source SHA.

No credentials or repository write permission. The same checked bytes go to every CI job
and deployment. A PR changing a machine-owned output fails before regeneration, so repair
cannot hide a handwritten mismatch. Historical analysis receipts/pins are not regenerable
outputs; their existing guards and review requirements remain in force.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
OUTPUTS = [
    'platform/src/generated/muhurta_undertakings.generated.ts',
    'platform/src/lib/retrieval/signal_glossary.generated.ts',
    'platform-mcp/src/resources/vidhi/registry_data.ts',
    'platform/src/generated/nirmana-writer-digests.json',
    'platform/src/generated/capability_estate_census.json',
    'platform/src/generated/capability_knowledge.snapshot.json',
    '00_ARCHITECTURE/control/registry_coverage_report.json',
    'platform/python-sidecar/services/gochara_kernel/implementation_digest.lock.json',
]
PROJECTION_OUTPUTS = [
    'platform/src/generated/projections/' + name + '.generated.json'
    for name in ('machine_census', 'chat_tool_defs', 'mcp_tool_registrations',
                 'docs_resource_catalog', 'web_tool_bridge', 'family_tool_defs',
                 'tool_search_index', 'mcp_surface_profiles', 'comparison_report')
] + ['platform-mcp/src/generated/mcp_surface_profiles.generated.ts',
     '00_ARCHITECTURE/briefs/retrieval_impl/R1_PROJECTION_COMPILER_REPORT.md']
OUTPUTS += PROJECTION_OUTPUTS
# These are governed historical receipts or database observations, not offline
# compiler outputs. Their existing review/hash guards remain authoritative.
SOURCE_RECORDS = ('platform/src/generated/harvest/', 'platform/src/generated/census/',
                  'platform/src/generated/concept_census.json',
                  'platform/src/generated/nirmana-analysis-receipts.ts',
                  'platform/src/generated/nirmana-l0-analysis-receipts.ts',
                  'platform/src/generated/nirmana-analysis-layer-pins.json')
MANIFEST = 'ci-generated-manifest.json'


def changed_outputs(paths):
    return [p for p in paths if p in OUTPUTS or
            (p.startswith('platform/src/generated/') and not any(p == record or (record.endswith('/') and p.startswith(record)) for record in SOURCE_RECORDS) and '/__tests__/' not in p and not p.endswith(('.test.ts', '.test.tsx')))]


def manifest(root: Path, sha: str, paths: list[str]) -> dict:
    return {'schema': 'ci.generated/1', 'source_sha': sha,
            'files': {p: hashlib.sha256((root / p).read_bytes()).hexdigest() for p in paths}}


def verify(root: Path, doc: dict, sha: str, allow_dirty_test: bool = False) -> list[str]:
    errors = []
    if doc.get('test_only') and not allow_dirty_test:
        errors.append('dirty local generation is test-only, not a reviewed CI artifact')
    if doc.get('schema') != 'ci.generated/1' or doc.get('source_sha') != sha:
        errors.append('generated overlay source SHA/schema mismatch')
    if not isinstance(doc.get('files'), dict) or not doc['files']:
        return errors + ['missing or empty generated file manifest']
    for path, digest in doc['files'].items():
        if path not in OUTPUTS and not (path.startswith('platform/src/generated/') and '..' not in Path(path).parts):
            errors.append(f'unexpected generated path: {path}')
            continue
        target = root / path
        if not target.is_file() or hashlib.sha256(target.read_bytes()).hexdigest() != digest:
            errors.append(f'generated byte mismatch: {path}')
    return errors


def git(*args):
    return subprocess.check_output(['git', *args], cwd=ROOT,
                                   env={**os.environ, 'GIT_OPTIONAL_LOCKS': '0'}, text=True).strip()


def dirty_sources():
    paths = set(git('diff', '--name-only', 'HEAD').splitlines())
    paths.update(git('ls-files', '--others', '--exclude-standard').splitlines())
    return paths - set(OUTPUTS) - {MANIFEST}


def generate(destination: Path, base: str | None):
    if base:
        changed = git('diff', '--name-only', base, 'HEAD').splitlines()
        bad = changed_outputs(changed)
        if bad:
            raise ValueError('machine-owned outputs must not be edited in branches: ' + ', '.join(bad))
    # Generate leaf mirrors before the census/snapshot dependency chain, then
    # independently check every compiler and the existing runtime digest guard.
    node_scripts = ['scripts/generate_muhurta_undertakings.ts',
                    'scripts/generate_signal_glossary_mirror.ts',
                    'scripts/generate_vidhi_registry_mirror.ts']
    for script in node_scripts:
        subprocess.run(['node', '--import', 'tsx', '--conditions=react-server', script], cwd=ROOT / 'platform', check=True)
    sidecar = ROOT / 'platform/python-sidecar'
    subprocess.run([sys.executable, '-m', 'services.gochara_kernel.implementation_registry', '--write'], cwd=sidecar, check=True)
    subprocess.run(['bash', 'platform/scripts/regenerate_generated.sh'], cwd=ROOT, check=True)
    for script in node_scripts:
        subprocess.run(['node', '--import', 'tsx', '--conditions=react-server', script, '--check'], cwd=ROOT / 'platform', check=True)
    subprocess.run([sys.executable, '-m', 'services.gochara_kernel.implementation_registry'], cwd=sidecar, check=True)
    subprocess.run(['bash', 'platform/scripts/regenerate_generated.sh', '--check'], cwd=ROOT, check=True)
    # UTC 'Z' regardless of the committer's timezone: a branch commit made at +05:30 otherwise fails the
    # date-stamped registry metric test (mcp_catalog_version.test.ts expects ...Z).
    projection_env = {**os.environ, 'CI_GENERATED_AT': subprocess.run(['git', 'show', '-s', '--date=format-local:%Y-%m-%dT%H:%M:%SZ', '--format=%cd', 'HEAD'], cwd=ROOT, env={**os.environ, 'TZ': 'UTC'}, capture_output=True, text=True, check=True).stdout.strip()}
    projection_cmd = ['node', '--import', 'tsx', '--conditions=react-server', 'scripts/manifest/generate_projections.ts']
    subprocess.run(projection_cmd, cwd=ROOT / 'platform', env=projection_env, check=True)
    first = {p: (ROOT / p).read_bytes() for p in PROJECTION_OUTPUTS}
    subprocess.run(projection_cmd, cwd=ROOT / 'platform', env=projection_env, check=True)
    changed = [p for p in PROJECTION_OUTPUTS if first[p] != (ROOT / p).read_bytes()]
    if changed:
        raise ValueError('nondeterministic projection outputs: ' + ', '.join(changed))
    destination.mkdir(parents=True, exist_ok=True)
    import shutil
    for path in OUTPUTS:
        target = destination / path
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / path, target)
    doc = manifest(ROOT, git('rev-parse', 'HEAD'), OUTPUTS)
    doc['test_only'] = bool(dirty_sources())
    (destination / MANIFEST).write_text(json.dumps(doc, indent=2) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('mode', choices=['generate', 'verify'])
    ap.add_argument('--destination', type=Path)
    ap.add_argument('--base')
    ap.add_argument('--sha')
    ap.add_argument('--manifest', type=Path, default=ROOT / MANIFEST)
    ap.add_argument('--allow-dirty-test', action='store_true', help='local compiler tests only; never set by restore-generated')
    ns = ap.parse_args()
    if ns.mode == 'generate':
        if not ns.destination:
            ap.error('--destination is required')
        generate(ns.destination, ns.base)
        return 0
    doc = json.loads(ns.manifest.read_text())
    # Require the full declared set in real artifacts, not just a self-consistent subset.
    errors = verify(ROOT, doc, ns.sha or git('rev-parse', 'HEAD'), ns.allow_dirty_test)
    if dirty_sources() and not ns.allow_dirty_test:
        errors.append('source checkout changed after its reviewed commit')
    if set(doc.get('files', {})) != set(OUTPUTS):
        errors.append('generated overlay is incomplete')
    for error in errors:
        print(error, file=sys.stderr)
    return bool(errors)


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        print(f'generated overlay refused: {exc}', file=sys.stderr)
        sys.exit(1)
