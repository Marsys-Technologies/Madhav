#!/usr/bin/env node
/**
 * generate_completeness_accounting.mjs - Elevation Campaign v2.1, Stream gamma (PURNA), Lane Omega-3.
 *
 * The Completeness Contract generator. Implements C7's `AccountingInvariantResult` type
 * (see ~/elev-v2-shared/contracts/C7_ACCOUNTING_INVARIANT_v1_0.md) exactly: for a given
 * (chart_id, domain) it computes the domain's TCI slice S, produces exactly one
 * `ConceptAccountingRow` per concept in S, assigns each to one of the five accounting states,
 * resolves real per-chart evidence PKs for served rows, and computes `pass` per C7's formula.
 *
 * INPUTS (upstream, read-only; both independently generated by Omega-1/Omega-2):
 *   - TOTAL_CONCEPT_INVENTORY_v1_0.json  (Omega-1, elev/gamma-Omega-tci)      - 14,073 concepts
 *   - DOMAIN_RELEVANCE_MAP_v1_0.json     (Omega-2, elev/gamma-Omega-relevance) - 14,073 rows
 * Paths default to the sibling worktrees but are overridable via env (TCI_PATH / RELEVANCE_PATH)
 * so the script keeps working once the branches merge and both artifacts land under this lane's
 * own capability_map/ directory.
 *
 * STATE ASSIGNMENT (per the Omega-3 brief + C7):
 *   row_count_per_canonical_chart[chart] > 0                              -> served
 *   row_count === 0 (or absent) AND computed_globally === true            -> empty_for_this_chart
 *   computed_globally === false                                          -> not_computed_globally
 *   superseded_by_aggregate  -> INTENTIONALLY UNUSED (see SUPERSEDED_NOTE below)
 *   excluded_by_named_rule   -> MUST NOT appear when auditing a slice S (C7 rule 2)
 *
 * EVIDENCE (C7 evidence table + rule 3):
 *   served               -> { tool, fact_ids }  fact_ids are REAL per-chart PKs resolved fresh
 *                           from the DB (chart_facts.fact_id or the owning L2+ table's PK), so
 *                           rule 3 ("fact_ids must resolve back to real ... values") holds by
 *                           construction. A served concept whose serving filter resolves to no
 *                           DB rows is recorded as an UNRESOLVED served row (fact_ids: []) and
 *                           counted honestly - it fails the evidence check and drops `pass`.
 *   empty_for_this_chart -> { fact_ids: [] }     query ran, zero rows for this chart (field present).
 *   not_computed_globally-> {}                   no evidence field required by C7.
 *
 * DB access: no local DATABASE_URL / pg module in this tree, so we shell out to `psql`
 * (the same 127.0.0.1:5433/amjis instance the postgres MCP uses). Connection comes from
 * env DATABASE_URL (required at run time; never hard-coded into this artifact).
 *
 * OUTPUTS (this lane's manifest scope, capability_map/**):
 *   COMPLETENESS_ACCOUNTING_<domain>_<chart8>_v1_0.json  (4 files, full AccountingInvariantResult)
 *   COMPLETENESS_ACCOUNTING_SUMMARY_v1_0.json            (the 4 headline results, no rows)
 */

