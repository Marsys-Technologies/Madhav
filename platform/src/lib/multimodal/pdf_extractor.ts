/**
 * pdf_extractor — deterministic PDF preview until Document Understanding
 * integration is implemented.
 */

export interface PdfExtractResult {
  /** Plain-text rendition of all pages, concatenated. */
  text: string
  /** Page count as reported by the extractor. */
  pageCount: number
  /** Whether real extraction ran (false = fixture fallback). */
  usedRealExtraction: boolean
}

export async function extractPdf(filename: string, bytes: Uint8Array): Promise<PdfExtractResult> {
  // Sniff page count from the linearised PDF %%EOF count heuristic (rough estimate).
  const buf = Buffer.from(bytes)
  const eofCount = buf.toString('binary').split('%%EOF').length - 1
  const pageCount = Math.max(1, eofCount)

  return {
    text: `[PDF FIXTURE] ${filename} — ${bytes.length} bytes, ~${pageCount} page(s).\n\n` +
          `This is a placeholder extraction generated by pdf_extractor.ts fixture path.\n` +
          `TODO(γ): Replace with real Vertex AI Document Understanding results once ` +
          `GOOGLE_CLOUD_PROJECT and GOOGLE_APPLICATION_CREDENTIALS are provisioned.`,
    pageCount,
    usedRealExtraction: false,
  }
}
